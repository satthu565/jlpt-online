import { endpointsData } from './endpoints-data.js';
import { openApiComponents } from './spec-data.js';
import { toYaml } from './yaml-serializer.js';

export function buildOpenApiSpec(): Record<string, unknown> {
  return {
    openapi: '3.1.0',
    info: {
      title: 'JLPT Online Product API',
      version: '1.0.0',
      description:
        'Hợp đồng API toàn bộ sản phẩm JLPT Online V1-V4 (hỗ trợ thi, luyện tập, SRS, planner, AI, thanh toán, quản trị)',
    },
    servers: [
      {
        url: 'http://localhost:4000',
        description: 'Local development API server',
      },
    ],
    components: openApiComponents,
    paths: endpointsData,
  };
}

export function generateOpenApiYaml(): string {
  const spec = buildOpenApiSpec();
  return `# AUTO-GENERATED BY F02 CONTRACT GENERATOR. DO NOT EDIT DIRECTLY.\n# To regenerate: pnpm contracts:generate\n\n${toYaml(spec)}\n`;
}
