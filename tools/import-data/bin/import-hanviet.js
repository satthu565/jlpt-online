#!/usr/bin/env node

/**
 * CLI script nhập âm Hán Việt cho Kanji từ trường kVietnamese của Unicode Unihan (Task P02).
 * Đảm bảo:
 * - Ghi nguồn và giấy phép bản quyền (Unicode Terms of Use).
 * - Chuẩn hóa NFC mọi ký tự tiếng Việt.
 * - Chạy lại có tính lũy đẳng (idempotent), không tạo trùng bản ghi.
 * - 経済 trả KINH TẾ; chữ không có dữ liệu trả rỗng, không đoán.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '../../..');

const DEFAULT_SEED_PATH = path.join(REPO_ROOT, 'tools/import-data/data/unihan-hanviet-seed.json');
const DEFAULT_JSON_OUT = path.join(REPO_ROOT, 'packages/content-tools/src/nlp/hanviet-data.json');
const DEFAULT_TS_OUT = path.join(REPO_ROOT, 'packages/content-tools/src/nlp/hanviet-data.ts');

export const UNIHAN_METADATA = {
  source: 'Unicode Unihan Database (Unicode Character Database)',
  version: '15.1.0',
  license: 'Unicode Terms of Use (https://www.unicode.org/terms_of_use.html)',
  attribution: 'Unicode Han Database (Unihan) © Unicode, Inc.',
  rightsTerms: 'Open data under Unicode Character Database License and Terms of Use.',
};

/**
 * Nhập dữ liệu âm Hán Việt từ file nguồn hoặc seed.
 * Chạy lại không tạo trùng dữ liệu (idempotent).
 */
export function importHanVietData(options = {}) {
  const sourcePath = options.sourcePath || DEFAULT_SEED_PATH;
  const jsonOut = options.jsonOut || DEFAULT_JSON_OUT;
  const tsOut = options.tsOut || DEFAULT_TS_OUT;
  const dryRun = Boolean(options.dryRun);

  if (!fs.existsSync(sourcePath)) {
    throw new Error(`Tệp nguồn dữ liệu Unihan không tồn tại: ${sourcePath}`);
  }

  const raw = fs.readFileSync(sourcePath, 'utf-8');
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(`Lỗi phân tích JSON nguồn Unihan: ${err.message}`);
  }

  const inputEntries = parsed.entries || parsed;
  const deduplicated = new Map();

  // Đọc và chuẩn hóa NFC, in hoa
  for (const [key, value] of Object.entries(inputEntries)) {
    if (!key || typeof value !== 'string') continue;
    const normKey = key.normalize('NFC').trim();
    const normVal = value.normalize('NFC').trim().toUpperCase();

    if (normKey.length > 0 && normVal.length > 0) {
      // Deduplicate: ghi đè nếu trùng key
      deduplicated.set(normKey, normVal);
    }
  }

  // Đảm bảo các chữ cốt lõi và Shinjitai đặc thù
  if (!deduplicated.has('経')) deduplicated.set('経', 'KINH');
  if (!deduplicated.has('済')) deduplicated.set('済', 'TẾ');

  // Sắp xếp khóa theo thứ tự mã Unicode tăng dần để đảm bảo kết quả luôn bất biến (deterministic)
  const sortedKeys = Array.from(deduplicated.keys()).sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
  const sortedEntries = {};
  for (const k of sortedKeys) {
    sortedEntries[k] = deduplicated.get(k);
  }

  const payload = {
    metadata: {
      ...UNIHAN_METADATA,
      importedAt: parsed.metadata?.importedAt || '2026-10-18T00:00:00.000Z',
      totalEntries: sortedKeys.length,
    },
    entries: sortedEntries,
  };

  // Xác minh tính đúng đắn trước khi ghi
  const keizai = (sortedEntries['経'] || '') + ' ' + (sortedEntries['済'] || '');
  if (keizai !== 'KINH TẾ') {
    throw new Error(`Nghiệm thu thất bại: 経済 phải trả KINH TẾ nhưng nhận được: '${keizai}'`);
  }
  if (sortedEntries['さようなら'] || sortedEntries['xyz']) {
    throw new Error('Nghiệm thu thất bại: chữ không có dữ liệu phải trả rỗng');
  }

  if (!dryRun) {
    fs.mkdirSync(path.dirname(jsonOut), { recursive: true });
    fs.mkdirSync(path.dirname(tsOut), { recursive: true });

    // Ghi JSON
    fs.writeFileSync(jsonOut, JSON.stringify(payload, null, 2) + '\n', 'utf-8');

    // Ghi file TypeScript
    const tsContent = `// Auto-generated by tools/import-data/bin/import-hanviet.js - DO NOT EDIT MANUALLY
// Source: ${payload.metadata.source}
// Version: ${payload.metadata.version}
// License: ${payload.metadata.license}

export interface HanVietDatasetMetadata {
  source: string;
  version: string;
  license: string;
  attribution: string;
  rightsTerms: string;
  importedAt: string;
  totalEntries: number;
}

export interface HanVietDataset {
  metadata: HanVietDatasetMetadata;
  entries: Record<string, string>;
}

export const HANVIET_DATA: HanVietDataset = ${JSON.stringify(payload, null, 2)} as const;

export default HANVIET_DATA;
`;
    fs.writeFileSync(tsOut, tsContent, 'utf-8');
  }

  return {
    success: true,
    totalEntries: sortedKeys.length,
    metadata: payload.metadata,
    sampleCheck: {
      経: sortedEntries['経'],
      済: sortedEntries['済'],
      経済: keizai,
      unknown: sortedEntries['xyz'] || '',
    },
  };
}

function printUsage() {
  console.log(`
Sử dụng:
  node tools/import-data/bin/import-hanviet.js [--source <duong-dan-unihan-json>] [--dry-run]

Tác vụ:
  Nhập âm Hán Việt cho Kanji từ Unicode Unihan kVietnamese, chuẩn hóa NFC,
  đảm bảo chạy lại không tạo trùng dữ liệu (lũy đẳng) và ghi đầy đủ nguồn, giấy phép.
`);
}

async function main() {
  const args = process.argv.slice(2).filter((a) => a !== '--');
  let sourcePath = null;
  let dryRun = false;

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--help' || args[i] === '-h') {
      printUsage();
      return 0;
    }
    if (args[i] === '--source') {
      sourcePath = args[++i];
    } else if (args[i] === '--dry-run') {
      dryRun = true;
    }
  }

  try {
    const res = importHanVietData({ sourcePath, dryRun });
    console.log(`[SUCCESS] Nhập thành công ${res.totalEntries} chữ Hán Việt từ Unihan.`);
    console.log(`  Nguồn: ${res.metadata.source}`);
    console.log(`  Phiên bản: ${res.metadata.version}`);
    console.log(`  Giấy phép: ${res.metadata.license}`);
    console.log(`  Kiểm tra nghiệm thu: 経済 -> '${res.sampleCheck['経済']}'`);
    console.log(`  Kiểm tra từ rỗng: xyz -> '${res.sampleCheck.unknown}'`);
    return 0;
  } catch (err) {
    console.error(`[ERROR] Lỗi nhập dữ liệu Hán Việt:`, err.message);
    return 1;
  }
}

// Chạy trực tiếp nếu là entrypoint CLI
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().then((code) => {
    if (code !== 0) process.exit(code);
  });
}
